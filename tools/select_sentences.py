"""Pick and order the recording prompts by diphone coverage.

A diphone is a pair of neighboring sounds (the "s-t" in "stop"). TTS models
learn sounds in context, so a good recording script covers as many different
sound pairs as possible, as early as possible.

This script:
  1. Reads the CMU ARCTIC prompt list (1,132 sentences).
  2. Turns each sentence into phonemes with espeak-ng, using the exact
     phonemizer Piper trains with.
  3. Greedily picks the sentence that adds the most new sound pairs
     (common pairs weigh more, and longer sentences are penalized slightly
     so we don't just pick long ones).
  4. Prints a coverage table and writes ../sentences.js (first 300, plus
     15 questions mixed in every 20 sentences).

Usage:
  pip install piper-tts
  git clone --depth 1 https://github.com/festvox/festvox.git
  python3 select_sentences.py festvox/src/vox_files/prompts/cmuarctic.data
"""
import json
import math
import os
import re
import sys
from collections import Counter

import piper
from piper.phonemize_espeak import EspeakPhonemizer

N_SENTENCES = 300
QUESTION_EVERY = 20
FIXES = {  # '--' reads awkwardly and confuses the phonemizer
    "arctic_a0282": "If you mean to insinuate, Brentwood began hotly.",
    "arctic_b0536": "Typhoid, did I tell you.",
}
QUESTIONS = [  # ARCTIC has almost no questions; these add rising intonation
    "Could you pass me the jar of honey on the top shelf?",
    "Is this the train that goes downtown, or the one to the airport?",
    "Why does toast always land butter side down?",
    "Have you ever tried mango with chili and lime?",
    "Which way is north from here?",
    "Exactly how many marbles are in that jar?",
    "Would you rather visit the mountains or the beach?",
    "Does anyone know where I left my keys?",
    "What time does the farmers market close on Sunday?",
    "How long does it take to drive across the state?",
    "Can you hear the owl hooting in the distance?",
    "Is it going to rain again tomorrow?",
    "Did you remember to feed the cat this morning?",
    "Where should we go for dinner tonight?",
    "Are you sure that's the right address?",
]

phonemizer = EspeakPhonemizer(os.path.join(os.path.dirname(piper.__file__), "espeak-ng-data"))


def phones(text):
    """Sentence -> list of phonemes, with '#' marking the start and end."""
    seq = ["#"]
    for sentence in phonemizer.phonemize("en-us", text):
        for ch in sentence:
            if ch in "ˈˌ.,!?;:—-…\"'() ":
                continue  # drop stress marks, punctuation and word gaps
            if ch == "ː" and len(seq) > 1:
                seq[-1] += ch  # length mark belongs to the previous vowel
                continue
            seq.append(ch)
    return seq + ["#"]


def main(path):
    raw = open(path, encoding="utf-8").read()
    prompts = re.findall(r'\(\s*(\S+)\s+"(.*)"\s*\)', raw)
    data = []
    for pid, text in prompts:
        p = phones(text)
        data.append({"id": pid, "text": FIXES.get(pid, text),
                     "len": len(p), "di": set(a + "|" + b for a, b in zip(p, p[1:]))})
    freq = Counter(d for x in data for d in x["di"])
    total_types = len(freq)

    chosen, seen, remaining = [], set(), list(data)
    while remaining:
        best = max(remaining, key=lambda x: sum(math.log1p(freq[d]) for d in x["di"] - seen) / math.sqrt(x["len"]))
        chosen.append(best)
        seen |= best["di"]
        remaining.remove(best)

    print(f"{len(data)} prompts, {total_types} distinct sound pairs")
    seen = set()
    for i, x in enumerate(chosen, 1):
        seen |= x["di"]
        if i in (50, 100, 150, 200, 250, 300):
            print(f"  first {i:3d} sentences cover {len(seen) / total_types:.1%} of sound pairs")

    out, q = [], 0
    for i, x in enumerate(chosen[:N_SENTENCES], 1):
        out.append({"id": x["id"].replace("arctic_", ""), "text": x["text"]})
        if i % QUESTION_EVERY == 0 and q < len(QUESTIONS):
            out.append({"id": f"q{q + 1:02d}", "text": QUESTIONS[q]})
            q += 1

    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "..", "sentences.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by tools/select_sentences.py. Do not edit by hand.\n"
                "// 300 CMU ARCTIC prompts reordered for diphone coverage (most useful first),\n"
                "// with 15 original questions mixed in every 20 sentences for question intonation.\n"
                "// Modified from CMU ARCTIC: reordered; '--' replaced with ',' in a0282 and b0536. See NOTICE.\n"
                "window.SENTENCES = " + json.dumps(out, indent=0, ensure_ascii=False) + ";\n")
    print(f"Wrote sentences.js with {len(out)} sentences")


if __name__ == "__main__":
    main(sys.argv[1])
